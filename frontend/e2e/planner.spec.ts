import {test,expect} from '@playwright/test';
test('configurar, calcular, reproducir, exportar y dimensionar flota',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 await expect(page.getByRole('heading',{name:'Una campaña. Todos los equipos.'})).toBeVisible();
 await expect(page.locator('body')).toHaveCSS('background-color','rgb(0, 0, 0)');
 await page.screenshot({path:'../docs/preview-inicial.png',fullPage:true});
 await page.getByRole('button',{name:'Flota',exact:true}).click();
 await page.getByRole('button',{name:'Añadir Generador'}).click();
 await page.getByRole('button',{name:'Generadores',exact:true}).click();
 await page.locator('.unit-list button').filter({hasText:'G03'}).click();
 await page.getByRole('spinbutton',{name:'Alcance',exact:true}).fill('350');
 await expect(page.getByRole('spinbutton',{name:'Alcance',exact:true})).toHaveValue('350');
 await page.getByRole('button',{name:'Calcular plan',exact:true}).click();
 await expect(page.locator('.result-panel')).toBeVisible({timeout:50000});
 await page.getByRole('button',{name:'Pausar',exact:true}).click();
 const slider=page.getByRole('slider',{name:'Tiempo de simulación'});
 await slider.fill('110');
 await page.getByRole('button',{name:'Mostrar rutas',exact:true}).click();
 await expect(page.locator('.gantt-row')).toHaveCount(6);
 await page.screenshot({path:'../docs/preview-plan.png',fullPage:true});
 await page.getByRole('button',{name:'Por máquina',exact:true}).click();
 await expect(page.locator('.gantt-row')).toHaveCount(10);
 const csv=page.waitForEvent('download');await page.getByRole('button',{name:'Coordenadas CSV'}).click();expect((await csv).suggestedFilename()).toBe('coordenadas-y-tiempos.csv');
 await page.getByRole('button',{name:'Modelo y referencias'}).click();
 await expect(page.getByRole('dialog')).toContainText('no certifica');
 await page.getByRole('button',{name:'Cerrar modelo'}).click();
 await page.getByRole('button',{name:'Escenario',exact:true}).filter({hasNot:page.locator('svg')}).click();
 await page.getByRole('button',{name:'Dimensionar la flota',exact:false}).click();
 await page.getByRole('spinbutton',{name:'Plazo máximo'}).fill('1000');
 await expect(page.locator('.result-panel')).toHaveCount(0);
 await page.getByRole('button',{name:'Calcular flota y plan'}).click();
 await expect(page.locator('.result-panel')).toBeVisible({timeout:50000});
 await expect(page.locator('.result-fleet')).toContainText('FLOTA RECOMENDADA');
 expect(errors).toEqual([]);
});
test('móvil y error de configuración visible',async({page})=>{
 await page.setViewportSize({width:390,height:844});await page.goto('/');
 await expect(page.getByRole('button',{name:'Calcular plan',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Proceso',exact:true}).click();
 await page.getByRole('spinbutton',{name:'Consumo por pozo'}).fill('50');
 await page.getByRole('button',{name:'Calcular plan',exact:true}).click();
 await expect(page.getByRole('alert')).toContainText('tanque');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
 await page.screenshot({path:'../docs/preview-mobile.png',fullPage:true});
});
